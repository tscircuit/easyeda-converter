import { mkdir, writeFile } from "node:fs/promises"
import { convertCircuitJsonToPcbSvg } from "circuit-to-svg"
import { convertEasyEdaJsonToCircuitJson } from "../lib/convert-easyeda-json-to-tscircuit-soup-json"
import { EasyEdaJsonSchema } from "../lib/schemas/easy-eda-json-schema"
import { generateFootprintTsx } from "../lib/websafe/generate-footprint-tsx"
import raw from "../tests/assets/C37616412.raweasy.json"
import { runTscircuitCode } from "tscircuit"

const out = "tests/repros/c37616412"
const intermediate = convertEasyEdaJsonToCircuitJson(
  EasyEdaJsonSchema.parse(raw),
)
const footprint = generateFootprintTsx(intermediate)
const unformattedSource = `// Generated by scripts/repro-c37616412.ts; do not edit the imported footprint.\nexport default () => (\n  <board width="14mm" height="12mm">\n    <chip name="U1" footprint={${footprint}} />\n  </board>\n)\n`
const formatContent = (filePath: string, content: string) => {
  const formatted = Bun.spawnSync(
    ["./node_modules/.bin/biome", "format", `--stdin-file-path=${filePath}`],
    { stdin: Buffer.from(content) },
  )
  if (formatted.exitCode !== 0) throw new Error(formatted.stderr.toString())
  return formatted.stdout.toString()
}
const source = formatContent(`${out}/index.circuit.tsx`, unformattedSource)
const circuitJson = await runTscircuitCode(source)
const notes = circuitJson.filter((e) => e.type === "pcb_fabrication_note_path")
const board = circuitJson.filter((e) => e.type === "pcb_board")
await mkdir(out, { recursive: true })
await writeFile(`${out}/index.circuit.tsx`, source)
await writeFile(
  `${out}/circuit.json`,
  formatContent(`${out}/circuit.json`, JSON.stringify(circuitJson)),
)
await writeFile(
  `${out}/fabrication.json`,
  formatContent(`${out}/fabrication.json`, JSON.stringify(notes)),
)
await writeFile(`${out}/pcb.svg`, convertCircuitJsonToPcbSvg(circuitJson))
await writeFile(
  `${out}/fabrication.svg`,
  convertCircuitJsonToPcbSvg([...board, ...notes]),
)
console.log(
  `Wrote unmodified importer output and native PCB evidence to ${out}`,
)
